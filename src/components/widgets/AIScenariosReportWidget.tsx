import React, { useState } from 'react';
import { useApp } from '../../context/AppContext';
import { aiPlatform } from '../../services/aiPlatform';
import { FileText, Copy, Check, Download, Layers, Sparkles, LineChart } from 'lucide-react';

export const AIScenariosReportWidget: React.FC = () => {
  const { holdings, marketData, language } = useApp();
  const isAr = language === 'AR';

  const [copied, setCopied] = useState(false);
  const [reportText, setReportText] = useState(() => aiPlatform.generateExecutiveReport(holdings, marketData, isAr));

  const totalVal = holdings.reduce((sum, h) => sum + (h.currentValueEGP || 0), 0) || 500000;
  const scenarios = aiPlatform.getScenarioComparison(totalVal);

  const handleCopy = () => {
    navigator.clipboard.writeText(reportText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleRefreshReport = () => {
    const fresh = aiPlatform.generateExecutiveReport(holdings, marketData, isAr);
    setReportText(fresh);
  };

  return (
    <div className="bg-[#0D1424] border border-slate-800 rounded-xl p-5 select-none space-y-5">
      {/* 1. Scenario Comparison Matrix Section */}
      <div className="space-y-3">
        <div className="flex items-center gap-2 border-b border-slate-800 pb-3">
          <div className="p-2 rounded-lg bg-indigo-500/20 text-indigo-400 border border-indigo-500/30">
            <LineChart className="w-5 h-5" />
          </div>
          <div>
            <h3 className="font-extrabold text-base text-white">
              {isAr ? 'مقارنة السيناريوهات المستقبلية للمحفظة (Scenario Comparison Matrix)' : 'Macro Scenario Comparison Matrix'}
            </h3>
            <p className="text-xs text-slate-400">
              {isAr ? 'تطور القيمة المتوقعة للمحفظة عبر 4 سيناريوهات اقتصادية مختلفة' : 'Projected portfolio growth across Base, Devaluation Shock, Bullion Rally, and FX Stabilization'}
            </p>
          </div>
        </div>

        {/* Comparison Grid */}
        <div className="grid grid-cols-1 sm:grid-cols-3 gap-3 font-mono text-xs">
          {scenarios.map((sc) => (
            <div key={sc.periodMonths} className="bg-slate-900/80 p-3.5 rounded-xl border border-slate-800 space-y-2">
              <div className="flex items-center justify-between border-b border-slate-800 pb-1.5 font-sans">
                <span className="font-bold text-amber-400 text-xs">{sc.periodMonths} {isAr ? 'أشهر' : 'Months'} Horizon</span>
                <span className="text-[10px] text-slate-500">Initial: {totalVal.toLocaleString()} EGP</span>
              </div>
              <div className="space-y-1.5 text-[11px] font-sans">
                <div className="flex items-center justify-between">
                  <span className="text-slate-300">{isAr ? 'السيناريو الأساسي:' : 'Base Case:'}</span>
                  <span className="text-amber-300 font-bold font-mono">{sc.baseCaseEGP.toLocaleString()} EGP</span>
                </div>
                <div className="flex items-center justify-between text-emerald-400">
                  <span>{isAr ? 'صدمة خفض الجنيه:' : 'Devaluation Shock:'}</span>
                  <span className="font-bold font-mono">{sc.devaluationShockEGP.toLocaleString()} EGP</span>
                </div>
                <div className="flex items-center justify-between text-indigo-300">
                  <span>{isAr ? 'صعود الذهب العالمي:' : 'Global Bullion Surge:'}</span>
                  <span className="font-bold font-mono">{sc.globalBullionRallyEGP.toLocaleString()} EGP</span>
                </div>
                <div className="flex items-center justify-between text-slate-400">
                  <span>{isAr ? 'استقرار سعر الصرف:' : 'EGP Stabilization:'}</span>
                  <span className="font-mono">{sc.egpStabilizationEGP.toLocaleString()} EGP</span>
                </div>
              </div>
            </div>
          ))}
        </div>
      </div>

      {/* 2. Natural Language Executive AI Report Section */}
      <div className="space-y-3 pt-2">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 border-b border-slate-800 pb-3">
          <div className="flex items-center gap-2">
            <div className="p-2 rounded-lg bg-amber-500/20 text-amber-400 border border-amber-500/30">
              <FileText className="w-5 h-5" />
            </div>
            <div>
              <h3 className="font-extrabold text-base text-white">
                {isAr ? 'التقرير التنفيذي للذكاء الاصطناعي (Natural Language AI Report)' : 'Executive AI Natural Language Report'}
              </h3>
              <p className="text-xs text-slate-400">
                {isAr ? 'تقرير استثماري كلي مفصل ومصاغ تلقائياً باللغة العربية والإنجليزي' : 'Comprehensive automated executive briefing generated by Gemini 3.6 Flash'}
              </p>
            </div>
          </div>

          <div className="flex items-center gap-2 self-start sm:self-auto">
            <button
              onClick={handleRefreshReport}
              className="px-3 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-semibold flex items-center gap-1 cursor-pointer transition-all"
            >
              <Sparkles className="w-3.5 h-3.5 text-amber-400" />
              <span>{isAr ? 'تحديث التقرير' : 'Regenerate Report'}</span>
            </button>
            <button
              onClick={handleCopy}
              className="px-3 py-1.5 rounded-lg bg-indigo-600 hover:bg-indigo-500 text-white text-xs font-semibold flex items-center gap-1 cursor-pointer shadow-md shadow-indigo-600/20 transition-all"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? (isAr ? 'تم النسخ' : 'Copied') : (isAr ? 'نسخ التقرير' : 'Copy Report')}</span>
            </button>
          </div>
        </div>

        {/* Report Output Box */}
        <div className="bg-slate-950 p-4 rounded-xl border border-slate-800 text-xs text-slate-200 leading-relaxed font-sans whitespace-pre-line max-h-80 overflow-y-auto">
          {reportText}
        </div>
      </div>
    </div>
  );
};
